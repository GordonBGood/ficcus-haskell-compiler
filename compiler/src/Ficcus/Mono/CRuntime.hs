{-# OPTIONS_GHC -Wall #-}
module Ficcus.Mono.CRuntime
  ( prelude
  )
  where


-- Ficcus, stage (iii) slice 1b: the runtime pieces that generated C needs besides `ficrt.h`
-- (the reference counting and the allocator stay in `targets/c/ficrt.h`, included first).
-- Strings are heap objects {header, byte length, UTF-8 bytes, NUL}; slices 1 to 3 never free them
-- (leak checking is off until STAGE4-PLAN). Floats print like JavaScript's Number toString.


prelude :: String
prelude = unlines
  [ "#include \"ficrt.h\""
  , "#include <stdio.h>"
  , "#include <math.h>"
  , "#include <stdint.h>"
  , ""
  , "#define FIC_TAG_STRING 0xFFF0u"
  , "typedef struct fic_string { fic_hdr h; int64_t len; char data[]; } fic_string;"
  , "#define FIC_STR(r) ((fic_string *)(r))"
  , ""
  , "#define FIC_SUB64(a, b) ((int64_t)((uint64_t)(a) - (uint64_t)(b)))"
  , "#define FIC_NEG64(a) ((int64_t)(0u - (uint64_t)(a)))"
  , ""
  , "static fic_ref fic_str_new(const char *p, int64_t n) {"
  , "  fic_string *s = (fic_string *)fic_alloc(sizeof(fic_string) + (size_t)n + 1, FIC_TAG_STRING, 0);"
  , "  s->len = n;"
  , "  if (n > 0) memcpy(s->data, p, (size_t)n);"
  , "  s->data[n] = 0;"
  , "  return &s->h;"
  , "}"
  , ""
  , "static fic_ref fic_str_append(fic_ref a, fic_ref b) {"
  , "  int64_t la = FIC_STR(a)->len, lb = FIC_STR(b)->len;"
  , "  fic_string *s = (fic_string *)fic_alloc(sizeof(fic_string) + (size_t)(la + lb) + 1, FIC_TAG_STRING, 0);"
  , "  s->len = la + lb;"
  , "  memcpy(s->data, FIC_STR(a)->data, (size_t)la);"
  , "  memcpy(s->data + la, FIC_STR(b)->data, (size_t)lb);"
  , "  s->data[la + lb] = 0;"
  , "  return &s->h;"
  , "}"
  , ""
  , "static uint8_t fic_str_eq(fic_ref a, fic_ref b) {"
  , "  return FIC_STR(a)->len == FIC_STR(b)->len && memcmp(FIC_STR(a)->data, FIC_STR(b)->data, (size_t)FIC_STR(a)->len) == 0;"
  , "}"
  , ""
  , "static int64_t fic_idiv(int64_t a, int64_t b) {         /* Elm: x // 0 is 0; wraps like every Int operation */"
  , "  if (b == 0) return 0;"
  , "  if (b == -1) return FIC_NEG64(a);"
  , "  return a / b;"
  , "}"
  , ""
  , "static int64_t fic_ipow(int64_t b, int64_t e) {         /* Int ^ Int by repeated squaring, wrapping */"
  , "  int64_t r = 1;"
  , "  if (e < 0) return 0;"
  , "  while (e > 0) { if (e & 1) r = FIC_MUL64(r, b); b = FIC_MUL64(b, b); e >>= 1; }"
  , "  return r;"
  , "}"
  , ""
  , "/* Float comparison as Elm's kernel does it: cmp(x, y) = x === y ? 0 : x < y ? -1 : 1, so NaN compares as GT */"
  , "static uint8_t fic_f_lt(double a, double b) { return a < b; }"
  , "static uint8_t fic_f_le(double a, double b) { return a < b || a == b; }"
  , "static uint8_t fic_f_gt(double a, double b) { return !(a < b || a == b); }"
  , "static uint8_t fic_f_ge(double a, double b) { return !(a < b); }"
  , ""
  , "static fic_ref fic_str_from_int(int64_t v) {"
  , "  char buf[32];"
  , "  int n = snprintf(buf, sizeof buf, \"%lld\", (long long)v);"
  , "  return fic_str_new(buf, n);"
  , "}"
  , ""
  , "/* a Float as JavaScript's Number.prototype.toString: the shortest digits that read back exactly */"
  , "static int fic_fmt_float(double x, char *out) {"
  , "  char e[40], digits[32];"
  , "  int p, k = 0, n, exp10, o = 0, i;"
  , "  if (x != x) return sprintf(out, \"NaN\");"
  , "  if (x == 0) return sprintf(out, \"0\");"
  , "  if (x > 1.7976931348623157e308) return sprintf(out, \"Infinity\");"
  , "  if (x < -1.7976931348623157e308) return sprintf(out, \"-Infinity\");"
  , "  if (x < 0) { out[o++] = '-'; x = -x; }"
  , "  for (p = 0; p < 17; p++) { snprintf(e, sizeof e, \"%.*e\", p, x); if (strtod(e, NULL) == x) break; }"
  , "  for (i = 0; e[i] != 'e'; i++) if (e[i] != '.') digits[k++] = e[i];"
  , "  exp10 = atoi(e + i + 1);"
  , "  while (k > 1 && digits[k - 1] == '0') k--;"
  , "  n = exp10 + 1;"
  , "  if (k <= n && n <= 21) {"
  , "    memcpy(out + o, digits, (size_t)k); o += k;"
  , "    for (i = 0; i < n - k; i++) out[o++] = '0';"
  , "  } else if (0 < n && n <= 21) {"
  , "    memcpy(out + o, digits, (size_t)n); o += n; out[o++] = '.';"
  , "    memcpy(out + o, digits + n, (size_t)(k - n)); o += k - n;"
  , "  } else if (-6 < n && n <= 0) {"
  , "    out[o++] = '0'; out[o++] = '.';"
  , "    for (i = 0; i < -n; i++) out[o++] = '0';"
  , "    memcpy(out + o, digits, (size_t)k); o += k;"
  , "  } else {"
  , "    out[o++] = digits[0];"
  , "    if (k > 1) { out[o++] = '.'; memcpy(out + o, digits + 1, (size_t)(k - 1)); o += k - 1; }"
  , "    o += sprintf(out + o, \"e%c%d\", n - 1 < 0 ? '-' : '+', n - 1 < 0 ? 1 - n : n - 1);"
  , "  }"
  , "  out[o] = 0;"
  , "  return o;"
  , "}"
  , ""
  , "static fic_ref fic_str_from_float(double x) {"
  , "  char buf[64];"
  , "  int n = fic_fmt_float(x, buf);"
  , "  return fic_str_new(buf, n);"
  , "}"
  , ""
  , "/* Debug.toString of a String: quoted, with Elm's escapes */"
  , "static fic_ref fic_show_string(fic_ref s) {"
  , "  int64_t i, n = FIC_STR(s)->len, o = 0;"
  , "  char *buf = (char *)malloc((size_t)(n * 2 + 3));"
  , "  fic_ref r;"
  , "  buf[o++] = '\"';"
  , "  for (i = 0; i < n; i++) {"
  , "    char c = FIC_STR(s)->data[i];"
  , "    if (c == '\"' || c == '\\\\') { buf[o++] = '\\\\'; buf[o++] = c; }"
  , "    else if (c == '\\n') { buf[o++] = '\\\\'; buf[o++] = 'n'; }"
  , "    else if (c == '\\t') { buf[o++] = '\\\\'; buf[o++] = 't'; }"
  , "    else if (c == '\\r') { buf[o++] = '\\\\'; buf[o++] = 'r'; }"
  , "    else if (c == '\\v') { buf[o++] = '\\\\'; buf[o++] = 'v'; }"
  , "    else if (c == 0) { buf[o++] = '\\\\'; buf[o++] = '0'; }"
  , "    else buf[o++] = c;"
  , "  }"
  , "  buf[o++] = '\"';"
  , "  r = fic_str_new(buf, o);"
  , "  free(buf);"
  , "  return r;"
  , "}"
  , ""
  , "/* Debug.log: `tag: value` on its own line */"
  , "static void fic_log(fic_ref tag, fic_ref shown) {"
  , "  fwrite(FIC_STR(tag)->data, 1, (size_t)FIC_STR(tag)->len, stdout);"
  , "  fputs(\": \", stdout);"
  , "  fwrite(FIC_STR(shown)->data, 1, (size_t)FIC_STR(shown)->len, stdout);"
  , "  fputc('\\n', stdout);"
  , "}"
  , "/* a log of () prints the tag alone: the reference outputs of targets/ have the `: ()` of Elm removed (run_all.py) */"
  , "static void fic_log_unit(fic_ref tag) {"
  , "  fwrite(FIC_STR(tag)->data, 1, (size_t)FIC_STR(tag)->len, stdout);"
  , "  fputc('\\n', stdout);"
  , "}"
  ]
