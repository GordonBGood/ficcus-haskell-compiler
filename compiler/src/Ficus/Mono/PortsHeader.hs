{-# OPTIONS_GHC -Wall #-}
module Ficus.Mono.PortsHeader
  ( portsHeader
  , portsHeaderPath
  )
  where


-- Ficus, effects slice E3a (docs/E3-PORTS-DESIGN.md D2): the header a C host includes, written beside the generated C as
-- `<Module>_ports.h` (the main module's name, dots as underscores) when the program has ports or flags other than (). It is the host
-- interface (runtime/fic_ports_api.h, the same text the program carries) and, per reachable port, a comment with its direction, Elm
-- type and JSON shape and a constant `FIC_PORT_<name>` for its name, so a misspelt port is a compile error in the host. Unused ports
-- are dead code in Elm (absent from `app.ports`, checked on elm0193) and here.


import qualified Data.Char as Char
import qualified Data.List as List
import qualified Data.Map.Strict as Map
import qualified System.FilePath as FP

import Ficus.Mono.Class (MType)
import Ficus.Mono.CRuntime (portsApi)
import Ficus.Mono.Ir
import Ficus.Mono.ManagerOrder (Entry)
import Ficus.Mono.ManagerTable (Slot(..), managerSlots)
import qualified Ficus.Mono.PortDesc as PortDesc


-- | the path of the header: beside the C file, named after the main module
portsHeaderPath :: FilePath -> String -> FilePath
portsHeaderPath target moduleName =
  FP.takeDirectory target FP.</> (map (\c -> if c == '.' then '_' else c) moduleName ++ "_ports.h")


-- | the text of the header, or Nothing for a program without ports and with () flags
portsHeader :: [Entry] -> String -> MProgram -> Maybe String
portsHeader order moduleName program =
  do  root <- mpMain program
      let byId = Map.fromList [ (mdClone d, d) | d <- mpClones program ]
          ports = [ (out, n, t) | SPort out n t <- managerSlots order byId root ]
          flags = case Map.lookup root byId >>= mdBody of
                    Just (MExpr _ (MCall (MExpr _ (MKernel "elm/core:Platform.worker" key)) _)) -> PortDesc.flagsOfKey key
                    _ -> Nothing
      if null ports && flags == Nothing then Nothing else Just (render ports flags)
  where
    guardName = "FIC_PORTS_" ++ map (\c -> if Char.isAlphaNum c then Char.toUpper c else '_') moduleName ++ "_H"
    render ports flags =
      unlines $
        [ "/* " ++ moduleName ++ "_ports.h -- generated by the Ficus compiler: the ports and flags of the program " ++ moduleName ++ " (do not edit) */"
        , "#ifndef " ++ guardName
        , "#define " ++ guardName
        , ""
        ]
        ++ lines portsApi
        ++ [ "" ]
        ++ concatMap portLines (List.sortOn (\(_, n, _) -> n) ports)
        ++ flagLines flags
        ++ [ "", "#endif" ]

    portLines :: (Bool, String, MType) -> [String]
    portLines (out, n, t) =
      [ "/* port " ++ n ++ (if out then " (outgoing: fic_port_subscribe): " else " (incoming: fic_port_send): ") ++ PortDesc.elmTypeText t
      , "   JSON: " ++ PortDesc.jsonShape t ++ (if out then "" else note t) ++ " */"
      , "#define FIC_PORT_" ++ n ++ " " ++ PortDesc.cString n
      , ""
      ]

    note t = if isRecordish t then "  (an object may have more fields, in any order)" else ""
    isRecordish t = '{' `elem` PortDesc.jsonShape t

    flagLines flags =
      case flags of
        Nothing -> []
        Just t ->
          [ "/* flags: " ++ PortDesc.elmTypeText t ++ "   JSON: " ++ PortDesc.jsonShape t
          , "   given to fic_app_start, or to the program in FIC_FLAGS (JSON text) or FIC_FLAGS_FILE (a file of it) */"
          ]
