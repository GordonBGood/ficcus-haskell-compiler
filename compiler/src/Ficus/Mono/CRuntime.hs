{-# OPTIONS_GHC -Wall #-}
{-# LANGUAGE TemplateHaskell #-}
module Ficus.Mono.CRuntime
  ( prelude
  , closureRuntime
  , jsArrayRuntime
  , stringRuntime
  , fdlibmRuntime
  , jsonRuntime
  , bytesRuntime
  , regexRuntime
  , vectorRuntime
  , sizedRuntime
  , sortRuntime
  , platformRuntime
  , schedRuntime
  , portsRuntime
  , portsApi
  )
  where


-- Ficus: the runtime pieces of generated C. `fic_rt.h` (header, allocator, counts, the generic drop, vectors; derived from
-- `targets/c/ficrt.h`, which the hand written programs keep using) comes first.
-- They are real C files in `runtime/` (compiled and tested standalone by `runtime/test.sh`) and are
-- embedded here at build time, in this order, as one text emitted at the top of each generated file.
-- Strings are heap objects {header, byte length, UTF-8 bytes, NUL}; slices 1 to 3 never free them.
-- Floats print like JavaScript's Number toString.


import Ficus.Mono.Embed (embedFiles)


prelude :: String
prelude =
  $(embedFiles
      [ "runtime/fic_rt.h"
      , "runtime/fic_base.h"
      , "runtime/fic_string.h"
      , "runtime/fic_num.h"
      , "runtime/fic_format.h"
      , "runtime/fic_debug.h"
      ])


-- the closure runtime (generated by runtime/gen_closure.py): emitted after the prelude only by programs that use closures
closureRuntime :: String
closureRuntime =
  $(embedFiles [ "runtime/fic_closure.h" ])


-- the primitives of Elm.JsArray (needs the closure runtime): emitted only by programs that use arrays
jsArrayRuntime :: String
jsArrayRuntime =
  $(embedFiles [ "runtime/fic_jsarray.h" ])


-- the String functions with code point semantics and the Unicode case tables (needs the closure runtime): emitted only by
-- programs that use one of them
stringRuntime :: String
stringRuntime =
  $(embedFiles [ "runtime/fic_case.h", "runtime/fic_ustring.h", "runtime/fic_parser.h" ])


-- the Float functions of V8 (fdlibm), decision L18: emitted only by programs that call one of them
fdlibmRuntime :: String
fdlibmRuntime =
  $(embedFiles [ "runtime/fic_fdlibm.h" ])


-- the kernel of elm/json (needs the closure, JsArray and String runtimes): emitted only by programs that use it
jsonRuntime :: String
jsonRuntime =
  $(embedFiles [ "runtime/fic_json.h" ])


-- the kernel of elm/bytes (needs the String runtime): emitted only by programs that use it
bytesRuntime :: String
bytesRuntime =
  $(embedFiles [ "runtime/fic_bytes.h" ])


-- the kernel of elm/regex (needs the String runtime and its case tables): emitted only by programs that use it
regexRuntime :: String
regexRuntime =
  $(embedFiles [ "runtime/fic_regex.h" ])


-- the flat Vector (V1; needs only the prelude): emitted only by programs that use it
vectorRuntime :: String
vectorRuntime =
  $(embedFiles [ "runtime/fic_vector.h" ])


-- the sized integers and Float32 (docs/SIZED-PLAN.md; needs only the prelude): emitted only by programs that use them
sizedRuntime :: String
sizedRuntime =
  $(embedFiles [ "runtime/fic_sized.h" ])


-- Powersort for the flat Vector (H21; needs the Vector and the closure runtime): emitted only by programs that sort a Vector or a List
sortRuntime :: String
sortRuntime =
  $(embedFiles [ "runtime/fic_sort.h" ])


-- E1 (docs/EFFECTS-CHECK.md): the platform objects (the static empty bag of `Cmd.none`/`Sub.none`); emitted only by programs that use them
platformRuntime :: String
platformRuntime =
  $(embedFiles [ "runtime/fic_platform.h" ])


-- E2 (docs/EFFECTS-CHECK.md steps 4 to 8): the scheduler, the managers' dispatch, the event loop (needs the closure runtime); emitted only
-- by programs that use a task, a bag or a manager
schedRuntime :: String
schedRuntime =
  $(embedFiles [ "runtime/fic_sched.h" ])


-- E3a, E3b (docs/E3-PORTS-DESIGN.md): the host interface of ports and flags (the declarations, then the definitions; needs the JSON
-- runtime, and the scheduler for its port part); emitted only by programs that have ports or flags other than ()
portsRuntime :: String
portsRuntime =
  $(embedFiles [ "runtime/fic_ports_api.h", "runtime/fic_ports_fic.h", "runtime/fic_ports.h" ])


-- E3a (D2): the declarations alone, the top of the generated `<Module>_ports.h` that a host includes
portsApi :: String
portsApi =
  $(embedFiles [ "runtime/fic_ports_api.h" ])
