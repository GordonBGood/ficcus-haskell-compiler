// gen_fdlibm_test.js: test inputs and node's results for the Float functions of fic_fdlibm.h (decision L18).
//   node gen_fdlibm_test.js bin DIR N [SEED]   one file per function in DIR: N records of (x, [y,] result) as little endian doubles
//   node gen_fdlibm_test.js embed N            the C header test_fdlibm_cases.h (N random inputs per function, plus the edge values)
const fs = require('fs');
const one = ['sin', 'cos', 'tan', 'asin', 'acos', 'atan', 'exp', 'log', 'log2', 'log10', 'log1p', 'expm1', 'sinh', 'cosh', 'tanh', 'asinh', 'acosh', 'atanh', 'cbrt'];
const two = ['atan2', 'pow'];
const mode = process.argv[2];
let seed = BigInt(process.argv[mode === 'bin' ? 5 : 4] || 12345);
function rnd() { seed = (seed * 6364136223846793005n + 1442695040888963407n) & 0xFFFFFFFFFFFFFFFFn; return seed >> 11n; }
function r01() { return Number(rnd()) / 2 ** 53; }
const dv = new DataView(new ArrayBuffer(8));
function bits(b) { dv.setBigUint64(0, b); return dv.getFloat64(0); }
const HALFPI = Math.PI / 2;
function gen(f, i) {
  const k = i % 12; let x;
  if (k === 0) x = (r01() * 2 - 1) * 4;
  else if (k === 1) x = (r01() * 2 - 1) * 100;
  else if (k === 2) x = (r01() * 2 - 1) * 1e6;
  else if (k === 3) x = Math.exp((r01() * 2 - 1) * 700) * (r01() < .5 ? -1 : 1);
  else if (k === 4) x = bits((rnd() << 11n) | (rnd() & 0x7ffn));            // any bit pattern
  else if (k === 5) x = r01();
  else if (k === 6) x = Math.round((r01() * 2 - 1) * 1e5) * HALFPI * (1 + (r01() - .5) * 1e-14);   // near multiples of pi/2
  else if (k === 7) x = Math.round((r01() * 2 - 1) * 40) * HALFPI + (r01() - .5) * 1e-9;
  else if (k === 8) x = (r01() * 2 - 1) * 1e-5 * (r01() < .5 ? 1e-290 : 1);        // tiny, subnormal
  else if (k === 9) x = (r01() * 2 - 1) * 1e22;
  else if (k === 10) x = (r01() * 2 - 1) * 30;
  else x = (r01() * 2 - 1) * 2;
  if (['log', 'log2', 'log10', 'log1p'].includes(f) && i % 12 !== 0) x = Math.abs(x);
  if (f === 'acosh') x = Math.abs(x) + 1 + (i % 5 ? 0 : -1);
  if (f === 'asin' || f === 'acos' || f === 'atanh') x = (r01() * 2 - 1) * (i % 3 ? 1 : 1.0000001) * (i % 4 ? 1 : 1e-3);
  return x;
}
const edge = [0, -0, 1, -1, 0.5, -0.5, 2, -2, 10, -10, 3, 0.1, 1e-300, -1e-300, 5e-324, -5e-324, 2.2250738585072014e-308, 1.7976931348623157e308,
  -1.7976931348623157e308, NaN, Infinity, -Infinity, Math.PI, -Math.PI, HALFPI, Math.PI * 2, 710, 709.78, -745.2, -745.13, 1e10, 1e22, 1e300, 20, 22, 23, 28, 0.9999999999999999, 1.0000000000000002, 2 ** 27, 2 ** 28, 2 ** 29, 2 ** -28, 2 ** -29, 2 ** -54, 2 ** -55];
function inputs(f, n) { const xs = edge.slice(); for (let i = 0; i < n; i++) xs.push(gen(f, i)); return xs; }
function pairs(f, n) {
  const ps = [];
  for (const a of edge.slice(0, 30)) for (const b of edge.slice(0, 30)) ps.push([a, b]);
  for (let i = 0; i < n; i++) {
    const k = i % 8; let a, b;
    if (f === 'atan2') { a = gen('sin', i); b = gen('sin', i + 3); if (k === 5) b = a * (0.5 + r01()); }
    else {
      if (k === 0) { a = r01() * 10; b = (r01() * 2 - 1) * 20; }
      else if (k === 1) { a = Math.abs(gen('sin', i)); b = (r01() * 2 - 1) * 5; }
      else if (k === 2) { a = r01() * 3; b = (r01() * 2 - 1) * 400; }
      else if (k === 3) { a = (r01() * 2 - 1) * 20; b = Math.round((r01() * 2 - 1) * 10); }
      else if (k === 4) { a = 1 + (r01() - .5) * 1e-6; b = (r01() * 2 - 1) * 1e9; }
      else if (k === 5) { a = Math.exp((r01() * 2 - 1) * 700); b = (r01() * 2 - 1) * 3; }
      else if (k === 6) { a = Math.round(r01() * 100); b = Math.round(r01() * 300) / 4; }
      else { a = Math.abs(bits((rnd() << 11n) | (rnd() & 0x7ffn))); b = (r01() * 2 - 1) * 2; }
    }
    ps.push([a, b]);
  }
  return ps;
}
function hex(x) { dv.setFloat64(0, x); return '0x' + dv.getBigUint64(0).toString(16).padStart(16, '0') + 'ULL'; }
if (mode === 'bin') {
  const dir = process.argv[3], n = +process.argv[4];
  fs.mkdirSync(dir, { recursive: true });
  for (const f of one) { const xs = inputs(f, n); const b = Buffer.alloc(16 * xs.length); xs.forEach((x, i) => { b.writeDoubleLE(x, 16 * i); b.writeDoubleLE(Math[f](x), 16 * i + 8); }); fs.writeFileSync(dir + '/' + f + '.bin', b); }
  for (const f of two) { const ps = pairs(f, n); const b = Buffer.alloc(24 * ps.length); ps.forEach(([a, c], i) => { b.writeDoubleLE(a, 24 * i); b.writeDoubleLE(c, 24 * i + 8); b.writeDoubleLE(f === 'pow' ? Math.pow(a, c) : Math.atan2(a, c), 24 * i + 16); }); fs.writeFileSync(dir + '/' + f + '.bin', b); }
} else {
  const n = +process.argv[3];
  let out = '/* generated by gen_fdlibm_test.js (node ' + process.version + ', V8 ' + process.versions.v8 + '): inputs and the results of Math.<f>, as IEEE bit patterns */\n';
  for (const f of one) { const xs = inputs(f, n); out += 'static const unsigned long long fdc_' + f + '[][2] = {\n' + xs.map(x => '{' + hex(x) + ',' + hex(Math[f](x)) + '}').join(',\n') + '};\n'; }
  for (const f of two) { const ps = pairs(f, n); out += 'static const unsigned long long fdc_' + f + '[][3] = {\n' + ps.map(([a, c]) => '{' + hex(a) + ',' + hex(c) + ',' + hex(f === 'pow' ? Math.pow(a, c) : Math.atan2(a, c)) + '}').join(',\n') + '};\n'; }
  fs.writeFileSync('test_fdlibm_cases.h', out);
}
