// Generates fic_case.h: the full Unicode case mappings (String.toUpper, String.toLower: decision L8) and the
// Cased / Case_Ignorable ranges (for the Final_Sigma rule of toLower), from the Unicode data that this node
// has (the version is written into the header: Unicode 15.1 with node 21.5).
//   node gen_case.js > fic_case.h
const fs = require("fs");
function entries(f) {
  const out = [];
  for (let cp = 0; cp <= 0x10FFFF; cp++) {
    if (cp >= 0xD800 && cp <= 0xDFFF) continue;
    const s = String.fromCodePoint(cp), m = f(s);
    if (m !== s) out.push([cp, Array.from(m).map(c => c.codePointAt(0))]);
  }
  return out;
}
function ranges(re) {
  const out = []; let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp <= 0x10FFFF && !(cp >= 0xD800 && cp <= 0xDFFF) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  return out;
}
const up = entries(s => s.toUpperCase()), lo = entries(s => s.toLowerCase());
const cased = ranges(/^\p{Cased}$/u), ign = ranges(/^\p{Case_Ignorable}$/u);
const pad = a => { while (a.length < 3) a.push(0); return a; };
const maps = (name, list) => "static const fic_case_map " + name + "[] = {\n" +
  list.map(([cp, m]) => "  {0x" + cp.toString(16).toUpperCase() + "u, {" + pad(m.slice()).map(x => "0x" + x.toString(16).toUpperCase() + "u").join(",") + "}, " + m.length + "}").join(",\n") + "\n};\n" +
  "#define " + name.toUpperCase() + "_N " + list.length + "\n";
const rng = (name, list) => "static const fic_case_range " + name + "[] = {\n" +
  list.map(([a, b]) => "  {0x" + a.toString(16).toUpperCase() + "u, 0x" + b.toString(16).toUpperCase() + "u}").join(",\n") + "\n};\n" +
  "#define " + name.toUpperCase() + "_N " + list.length + "\n";
// the simple (one code point) mappings for Char.toUpper and Char.toLower come from UnicodeData.txt (fields 12 and 13) of the
// Unicode data package of this machine, restricted to code points that node's Unicode (15.1) has assigned
function simple(field) {
  const out = [];
  const assigned = cp => !/^\p{Cn}$/u.test(String.fromCodePoint(cp));
  for (const line of fs.readFileSync("/usr/share/unicode/ucd/UnicodeData.txt", "utf8").split("\n")) {
    const f = line.split(";");
    if (f.length < 14 || f[field] === "") continue;
    const cp = parseInt(f[0], 16), to = parseInt(f[field], 16);
    if (cp >= 0xD800 && cp <= 0xDFFF) continue;
    if (assigned(cp) && assigned(to)) out.push([cp, [to]]);
  }
  return out.sort((a, b) => a[0] - b[0]);
}
const supper = simple(12), slower = simple(13);
