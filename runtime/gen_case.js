console.log("typedef struct { uint32_t cp; uint32_t to[3]; uint8_t n; } fic_case_map;");
console.log("typedef struct { uint32_t lo, hi; } fic_case_range;");
console.log(maps("fic_upper_tab", up));
console.log(maps("fic_lower_tab", lo));
console.log(maps("fic_supper_tab", supper));
console.log(maps("fic_slower_tab", slower));
