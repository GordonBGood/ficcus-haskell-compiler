#!/usr/bin/env python3
"""Generates fic_closure.h: the closure runtime (uniform word ABI, arity checked at run time, like Elm's F2..F9/A2..A9).
Usage: python3 runtime/gen_closure.py > runtime/fic_closure.h      (the output is committed; MAXA below is the limit)"""
MAXA = 9

def args(n, p="a"): return ", ".join("fic_word %s%d" % (p, i) for i in range(n))
def names(n, p="a"): return ", ".join("%s%d" % (p, i) for i in range(n))

out = []
w = out.append
w("""/* generated by runtime/gen_closure.py: do not edit.  The closure runtime of generated programs (STAGE3-PLAN slice 3b).

   ABI. Every closure argument and result travels as a fic_word (an 8 byte union: i64, f64, u32, u8, reference).
   A struct goes through a closure boxed (a reference), so the code of a closure never depends on the key of its
   caller (addition 4 of the plan). A closure object is { header, code, captured values }; `code` points to a static
   fic_code { entry function, arity }, so the object keeps the layout of FIC_TAG_CLOSURE (the generic drop skips
   one word after the header). The entry function of arity n is  fic_word f(fic_ref self, fic_word a0 .. a(n-1)).

   fic_ap<n>(f, mask, a0..) calls f with n arguments and checks the arity of f at run time:
     arity == n  the entry function is called;
     arity  > n  a partial application (a closure of the remaining arity, holding f and the arguments) is returned;
     arity  < n  f is called with its first arity arguments and the result (a closure) with the rest.
   Ownership (STAGE4-PLAN sections 6 and 8): f is BORROWED, every argument is CONSUMED (owned by the callee, or stored in the partial
   application), the result is owned. The entry function gets `self` borrowed and its arguments owned. A partial application takes a count on f;
   applying one gives each reference argument it holds a count (it may be shared). Over-application drops the intermediate closure.
   `mask` has bit i set when argument i is a reference. A partial application keeps it, so that a later drop can
   release the references among its arguments (the generic drop of fic_rt.h releases them: fun, then the references among the first `nargs` arguments). */

/* gcc may inline the arity dispatch below into a call of a known closure and then "see" the dead branch that calls an
   entry function with too few arguments; that branch is never taken (the arity is checked), so the warning is false */
#if defined(__GNUC__) && !defined(__clang__)
#pragma GCC diagnostic ignored "-Wmaybe-uninitialized"
#endif

/* fic_word, fic_code, fic_clo and fic_pap are defined in fic_rt.h (the generic drop reads them) */

static fic_word fic_w_i(int64_t v) { fic_word w; w.i = 0; w.i = v; return w; }
static fic_word fic_w_d(double v) { fic_word w; w.i = 0; w.d = v; return w; }
static fic_word fic_w_c(uint32_t v) { fic_word w; w.i = 0; w.c = v; return w; }
static fic_word fic_w_b(uint8_t v) { fic_word w; w.i = 0; w.b = v; return w; }
static fic_word fic_w_p(fic_ref v) { fic_word w; w.i = 0; w.p = v; return w; }

#define FIC_CLO(r) ((fic_clo *)(r))
""")
for n in range(1, MAXA + 1):
    w("typedef fic_word (*fic_fn%d)(fic_ref%s);" % (n, "".join(", fic_word" for _ in range(n))))
w("")
# partial application entry functions: arity k, j arguments held, k-j remaining
for k in range(2, MAXA + 1):
    for j in range(1, k):
        r = k - j
        w("static fic_word fic_pap_%d_%d(fic_ref self%s) {" % (k, j, "".join(", fic_word b%d" % i for i in range(r))))
        w("  fic_pap *p = (fic_pap *)self;")
        w("  fic_ref f = p->fun;")
        w("  unsigned long long m = p->mask;")
        # the arguments held by the partial application go to the function owned: the partial application may be shared, so each
        # reference among them gets a count (the arguments of this call are owned already)
        for i in range(j):
            w("  if ((m >> %d) & 1u) FIC_RC_DUP(p->args[%d].p);" % (i, i))
        w("  return ((fic_fn%d)FIC_CLO(f)->code->fn)(f%s%s);" % (k, "".join(", p->args[%d]" % i for i in range(j)), "".join(", b%d" % i for i in range(r))))
        w("}")
w("")
w("static const fic_code fic_pap_code[%d][%d] = {" % (MAXA + 1, MAXA + 1))
for k in range(MAXA + 1):
    row = []
    for j in range(MAXA + 1):
        row.append("{ (void (*)(void))fic_pap_%d_%d, %du FIC_CODE_OWN0 }" % (k, j, k - j) if 2 <= k and 1 <= j < k else "{ 0, 0u FIC_CODE_OWN0 }")
    w("  { " + ", ".join(row) + " },")
w("};")
w("""
static fic_ref fic_mkpap(fic_ref f, unsigned k, unsigned j, uint32_t mask, const fic_word *a) {
  fic_pap *p = (fic_pap *)fic_alloc(sizeof(fic_pap) + (size_t)j * sizeof(fic_word), FIC_TAG_PAP, 1);
  unsigned i;
  p->code = &fic_pap_code[k][j];
  p->fun = f;
  FIC_RC_DUP(f);                               /* f is borrowed by the caller: the partial application holds its own count */
  p->mask = mask;
  p->nargs = j;
  for (i = 0; i < j; i++) p->args[i] = a[i];
  return &p->h;
}
""")
for n in range(1, MAXA + 1):
    w("static fic_word fic_ap%d(fic_ref f, uint32_t mask, %s) {" % (n, args(n)))
    w("  const fic_code *c = FIC_CLO(f)->code;")
    w("  unsigned k = c->arity;")
    w("  if (k == %du) return ((fic_fn%d)c->fn)(f, %s);" % (n, n, names(n)))
    w("  if (k > %du) { fic_word as[%d]; %s return fic_w_p(fic_mkpap(f, k, %du, mask, as)); }" % (n, n, " ".join("as[%d] = a%d;" % (i, i) for i in range(n)), n))
    if n > 1:
        w("  switch (k) {")
        for k in range(1, n):
            w("  case %du: { fic_word r = ((fic_fn%d)c->fn)(f, %s); fic_word res = fic_ap%d(r.p, mask >> %d, %s); FIC_RC_DROP(r.p); return res; }" % (k, k, names(k), n - k, k, ", ".join("a%d" % i for i in range(k, n))))
        w("  default: break;")
        w("  }")
    w("  abort();")
    w("}")
    w("")
w("""/* fic_ap<n>_own below frees a partial application; inlined into a call of a closure that gcc knows is a static object, the branch
   is dead (a static object is never a partial application with count 1), but gcc reports the free */
#if defined(__GNUC__) && !defined(__clang__) && __GNUC__ >= 11
#pragma GCC diagnostic ignored "-Wfree-nonheap-object"
#endif
""")
# S6, unique PAP stealing: fic_ap<n>_own consumes f (the Rc pass uses it when the call is the last use of an owned function value).
w("""/* S6 (STAGE4-PLAN section 6): fic_ap<n>_own(f, mask, a0..) is fic_ap<n> that CONSUMES f. When f is a partial application that nobody
   else holds (count 1) and this call completes it, the arguments it holds are MOVED to the function (no counts are touched, so a
   unique value held by the partial application is still unique in the function) and the partial application is freed before the
   call; otherwise f is called as by fic_ap<n> and dropped afterwards. */""")
for n in range(1, MAXA + 1):
    w("static fic_word fic_ap%d_own(fic_ref f, uint32_t mask, %s);" % (n, args(n)))
w("")
for n in range(1, MAXA + 1):
    w("static fic_word fic_ap%d_own(fic_ref f, uint32_t mask, %s) {" % (n, args(n)))
    w("  fic_word r;")
    # S7 part 3: a closure object that nobody else holds, called with exactly its arity: its second entry takes the captured values out
    w("#ifdef FIC_RC")
    w("  if (f->tag == FIC_TAG_CLOSURE && f->rc == 1) {")
    w("    const fic_code *c = FIC_CLO(f)->code;")
    w("    if (c->arity == %du && c->own != 0) return ((fic_fn%d)c->own)(f, %s);" % (n, n, names(n)))
    w("  }")
    w("#endif")
    if n < MAXA:
        w("#ifdef FIC_RC")
        w("  if (f->tag == FIC_TAG_PAP && f->rc == 1) {")
        w("    fic_pap *p = (fic_pap *)f;")
        w("    fic_ref g = p->fun;")
        w("    if (FIC_CLO(g)->code->arity == p->nargs + %du) {" % n)
        w("      fic_word s[%d];" % (MAXA - n))
        w("      unsigned i, j = p->nargs;")
        w("      uint32_t m = p->mask | (mask << j);")
        w("      for (i = 0; i < j; i++) s[i] = p->args[i];")
        w("      fic_free_obj(f);                          /* the shell only: its count on the function and on the arguments passes on */")
        w("      FIC_STAT(fic_n_pap_steal++);")
        w("      switch (j) {                              /* the function is consumed in turn: it may be a unique partial application itself */")
        for j in range(1, MAXA - n + 1):
            w("      case %du: return fic_ap%d_own(g, m, %s, %s);" % (j, j + n, ", ".join("s[%d]" % i for i in range(j)), names(n)))
        w("      default: abort();")
        w("      }")
        w("    }")
        w("  }")
        w("#endif")
    w("  r = fic_ap%d(f, mask, %s);" % (n, names(n)))
    w("  FIC_RC_DROP(f);")
    w("  return r;")
    w("}")
    w("")
print("\n".join(out))
