// Generates test_ustring_cases.h (the inputs, as UTF-8 byte arrays) and test_ustring.expected (what node gives for
// toUpperCase, toLowerCase, code point length, slice by code points, words as Elm's kernel defines it) for test_ustring.c.
//   node gen_ustring_test.js
const fs = require("fs");
let seed = 12345;
const rnd = n => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed % n; };
const pool = ["a", "B", "z", "Z", " ", " ", "\t", "\n", " ", " ", "　", "﻿", "ß", "ǆ", "ŉ", "ΐ", "σ", "Σ", "ς", "Ά", "İ", "ı", "é", "É", "ﬁ", "ᾳ", "ǅ", "Ǆ", "ꭰ", "Ꭰ", "😀", "𐐨", "𐐀", "'", ".", "0", "ÿ", "Ÿ", "℃", "Ω", "ω", "'", "ͅ", "­"];
const cases = [""];
for (const p of pool) cases.push(p);
for (const s of ["ΑΣ", "ΑΣ ", "Σ", "ΑΣΑ", "Α.Σ", "Α­Σ", "ΑΣ.Α", "ΑΣͅ", " Σ", "aΣ", "AΣb", "ΣΣ", "ΑΣΣ", "ὈΔΥΣΣΕΎΣ", "ΧΑΟΣ", "Straße", "ǰ", "ﬃ", "  hello   world  ", "\n a\tb c　d "]) cases.push(s);
for (let i = 0; i < 400; i++) { let s = ""; const n = rnd(12); for (let k = 0; k < n; k++) s += pool[rnd(pool.length)]; cases.push(s); }
const bytes = s => Array.from(Buffer.from(s, "utf8"));
const cpLen = s => Array.from(s).length;
const hex = s => Buffer.from(s, "utf8").toString("hex");
const words = s => s.trim().split(/\s+/g);
const slice = (s, a, b) => { const c = Array.from(s); return c.slice(a, b).join(""); };
const pats = ["", "a", "ab", "é", " ", "ΑΣ", "aa", "\n", "\r\n"];
const numStrs = ["", "0", "-0", "+5", "-", "+", "12", "-12", "007", "9223372036854775807", "9223372036854775808", "-9223372036854775808", "-9223372036854775809", "12a", " 1", "1 ", "1.5", "1e3", ".5", "5.", "-.5e-3", "Infinity", "-Infinity", "NaN", "0x10", "1b", "1o", "1e", "e5", "+.", "1_0", "1.2.3", "1E5", "١٢", "0.1", "123456789012345678901234567890", "1e400", "4.9e-324", "2.5e+10"];
let h = "/* GENERATED by gen_ustring_test.js: do not edit. */\nstatic const char *fic_ut_cases[] = {\n";
let exp = "";
cases.forEach((s, i) => {
  h += '  "' + bytes(s).map(b => "\\x" + b.toString(16).padStart(2, "0")).join("") + '",\n';
  exp += i + " len " + cpLen(s) + " up " + hex(s.toUpperCase()) + " lo " + hex(s.toLowerCase()) + " words " + words(s).map(hex).join(",") + "\n";
  for (const [a, b] of [[0, 1], [1, 3], [-2, 100], [2, -1], [3, 2], [-100, 2], [0, 0]]) exp += i + " slice " + a + " " + b + " " + hex(slice(s, a, b)) + "\n";
  exp += i + " rev " + hex(Array.from(s).reverse().join("")) + " trim " + hex(s.trim()) + " tl " + hex(s.replace(/^\s+/, "")) + " tr " + hex(s.replace(/\s+$/, "")) + " lines " + s.split(/\r\n|\r|\n/g).map(hex).join(",") + "\n";
  pats.forEach((p, j) => {
    const cps = Array.from(s);
    const idx = []; if (p.length) { let k = 0, at; while ((at = s.indexOf(p, k)) > -1) { idx.push(Array.from(s.slice(0, at)).length); k = at + p.length; } }
    const sp = p === "" ? cps : s.split(p);
    exp += i + " pat " + j + " has " + (s.indexOf(p) >= 0 ? 1 : 0) + " sw " + (s.startsWith(p) ? 1 : 0) + " ew " + (s.endsWith(p) ? 1 : 0) + " idx " + idx.join(",") + " split " + sp.map(hex).join(",") + "\n";
  });
});
numStrs.forEach((t, j) => {
  let ti = "N";
  { let total = 0n, ok = t.length > 0; const c0 = t[0]; const start = (c0 === "+" || c0 === "-") ? 1 : 0; for (let k = start; k < t.length; k++) { if (t[k] < "0" || t[k] > "9") { ok = false; break; } total = total * 10n + BigInt(t.charCodeAt(k) - 48); } if (t.length === start) ok = false; if (ok) { const v = c0 === "-" ? -total : total; if (v >= -(2n ** 63n) && v <= 2n ** 63n - 1n) ti = v.toString(); } }
  let tf = "N";
  if (!(t.length === 0 || /[\sxbo]/.test(t))) { const n = +t; if (n === n) tf = Object.is(n, -0) ? "-0" : String(n); }
  exp += "num " + j + " int " + ti + " float " + tf + "\n";
});
h += "};\nstatic const char *fic_ut_pats[] = {\n" + pats.map(p => '  "' + bytes(p).map(b => "\\x" + b.toString(16).padStart(2, "0")).join("") + '",').join("\n") + "\n};\n#define FIC_UT_P " + pats.length + "\n";
h += "static const char *fic_ut_nums[] = {\n" + numStrs.map(p => '  "' + bytes(p).map(b => "\\x" + b.toString(16).padStart(2, "0")).join("") + '",').join("\n") + "\n};\n#define FIC_UT_M " + numStrs.length + "\n";
h += "#define FIC_UT_N " + cases.length + "\n";
fs.writeFileSync("test_ustring_cases.h", h);
fs.writeFileSync("test_ustring.expected", exp);
console.log(cases.length + " cases");
