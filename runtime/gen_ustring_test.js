// Generates test_ustring_cases.h (the inputs, as UTF-8 byte arrays) and test_ustring.expected (what node gives for
// toUpperCase, toLowerCase, code point length, slice by code points, words as Elm's kernel defines it) for test_ustring.c.
//   node gen_ustring_test.js
const fs = require("fs");
let seed = 12345;
const rnd = n => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed % n; };
const pool = ["a", "B", "z", "Z", " ", " ", "\t", "\n", " ", " ", "　", "﻿", "ß", "ǆ", "ŉ", "ΐ", "σ", "Σ", "ς", "Ά", "İ", "ı", "é", "É", "ﬁ", "ᾳ", "ǅ", "Ǆ", "ꭰ", "Ꭰ", "😀", "𐐨", "𐐀", "'", ".", "0", "ÿ", "Ÿ", "℃", "Ω", "ω", "'", "ͅ", "­"];
const cases = [""];
for (const p of pool) cases.push(p);
for (const s of ["ΑΣ", "ΑΣ ", "Σ", "ΑΣΑ", "Α.Σ", "Α­Σ", "ΑΣ.Α", "ΑΣͅ", " Σ", "aΣ", "AΣb", "ΣΣ", "ΑΣΣ", "ὈΔΥΣΣΕΎΣ", "ΧΑΟΣ", "Straße", "ǰ", "ﬃ", "  hello   world  ", "\n a\tb c　d "]) cases.push(s);
for (let i = 0; i < 400; i++) { let s = ""; const n = rnd(12); for (let k = 0; k < n; k++) s += pool[rnd(pool.length)]; cases.push(s); }
const bytes = s => Array.from(Buffer.from(s, "utf8"));
const cpLen = s => Array.from(s).length;
const hex = s => Buffer.from(s, "utf8").toString("hex");
const words = s => s.trim().split(/\s+/g);
const slice = (s, a, b) => { const c = Array.from(s); return c.slice(a, b).join(""); };
let h = "/* GENERATED by gen_ustring_test.js: do not edit. */\nstatic const char *fic_ut_cases[] = {\n";
let exp = "";
cases.forEach((s, i) => {
  h += '  "' + bytes(s).map(b => "\\x" + b.toString(16).padStart(2, "0")).join("") + '",\n';
  exp += i + " len " + cpLen(s) + " up " + hex(s.toUpperCase()) + " lo " + hex(s.toLowerCase()) + " words " + words(s).map(hex).join(",") + "\n";
  for (const [a, b] of [[0, 1], [1, 3], [-2, 100], [2, -1], [3, 2], [-100, 2], [0, 0]]) exp += i + " slice " + a + " " + b + " " + hex(slice(s, a, b)) + "\n";
});
h += "};\n#define FIC_UT_N " + cases.length + "\n";
fs.writeFileSync("test_ustring_cases.h", h);
fs.writeFileSync("test_ustring.expected", exp);
console.log(cases.length + " cases");
