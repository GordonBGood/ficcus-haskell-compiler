#!/usr/bin/env python3
"""gen_sized.py -- writes the overlay modules of the sized integers and Float32 (docs/SIZED-PLAN.md): overlay/Int8.elm ... overlay/Float64.elm.
The bodies of the members and of the module functions that are kernels only give the types (Ficcus.Mono.Sized); the rest is Elm.
Run from the repository root: python3 ficcus-tools/gen_sized.py   (the output is checked in; `--check` fails when it differs)."""
import os, sys

INTS = [("Int8", 8, True), ("Int16", 16, True), ("Int32", 32, True),
        ("Word8", 8, False), ("Word16", 16, False), ("Word32", 32, False), ("Word64", 64, False)]

HEADER = """{-| Ficcus (generated by ficcus-tools/gen_sized.py, do not edit; docs/SIZED-PLAN.md): @DOC@

The operators, comparisons, `Dict` keys and `List.sort` work through the members below (decision A3); the specializer replaces every
member and every function marked (kernel) by the C operation of runtime/fic_sized.h, so the bodies only give the types. The module is
added to the source directories of `.c` and `.mono` builds (Ficcus.Mono.Overlay); a module `@T@` of the project or of a package of the
same name wins over this one (Build.crawlModule). `@T@(..)` is exported so that the members are visible to the type checker.
-}
"""

def member(name, sig, params, body):
    return f"        {name} : {sig}\n        {name} {params} =\n            {body}\n"

def int_module(T, bits, signed):
    lo = -(2 ** (bits - 1)) if signed else 0
    hi = 2 ** (bits - 1) - 1 if signed else (2 ** bits - 1)
    doc = (f"the {'signed' if signed else 'unsigned'} {bits} bit integer `@T@`, {lo} to {hi}. Arithmetic wraps around (two's complement, no check, no trap); "
           "`//`, `modBy` and `remainderBy` by zero give 0. Literals are checked against the range at compile time.")
    ms = [("add", f"{T} -> {T} -> {T}", "a _", "a"), ("sub", f"{T} -> {T} -> {T}", "a _", "a"), ("mul", f"{T} -> {T} -> {T}", "a _", "a"),
          ("pow", f"{T} -> {T} -> {T}", "a _", "a"), ("neg", f"{T} -> {T}", "a", "a"), ("abs", f"{T} -> {T}", "a", "a"),
          ("fromInt", f"Int -> {T}", "_", f"Fic{T}Builtin"), ("compare", f"{T} -> {T} -> Order", "_ _", "EQ"),
          ("idiv", f"{T} -> {T} -> {T}", "a _", "a"), ("mod", f"{T} -> {T} -> {T}", "a _", "a"), ("rem", f"{T} -> {T} -> {T}", "a _", "a")]
    maxv = "fromInt -1" if (T == "Word64") else f"fromInt {hi}"
    minv = f"fromInt {lo}"
    if T == "Word64":
        fromstr = f"""fromString : String -> Maybe {T}
fromString s =
    if String.isEmpty s then
        Nothing

    else
        fromStringHelp (String.toList s) (fromInt 0)


fromStringHelp : List Char -> {T} -> Maybe {T}
fromStringHelp chars acc =
    case chars of
        [] ->
            Just acc

        c :: rest ->
            let
                d =
                    Char.toCode c - 48
            in
            if d < 0 || d > 9 then
                Nothing

            else if acc > fromInt 1844674407370955161 || (acc == fromInt 1844674407370955161 && d > 5) then
                Nothing

            else
                fromStringHelp rest (acc * fromInt 10 + fromInt d)
"""
    else:
        neg = "" if signed else "n >= 0 && "
        fromstr = f"""fromString : String -> Maybe {T}
fromString s =
    case String.toInt s of
        Just n ->
            if {neg}n >= {lo} && n <= {hi} then
                Just (fromInt n)

            else
                Nothing

        Nothing ->
            Nothing
"""
    body = HEADER.replace('@DOC@', doc).replace('@T@', T)
    body = "module %s exposing\n    ( %s(..)\n    , fromInt, toInt, toString, fromString, minValue, maxValue\n    , and, or, xor, complement, shiftLeftBy, shiftRightBy, popCount\n    )\n\n" % (T, T) + body
    tmpl = """
import Basics exposing (Bool, Int, Order(..), (&&), (*), (+), (-), (<), (<=), (==), (>), (>=), (||))
import Char
import List exposing (List)
import Maybe exposing (Maybe(..))
import String exposing (String)


{-| The constructor is never built: it marks the type as the built-in one.
-}
type @T@
    = Fic@T@Builtin
    where
@MEMBERS@

-- KERNEL FUNCTIONS (types only)


{-| (kernel) the low @BITS@ bits of the `Int`, as a @SGN@ number: the value wraps around
-}
fromInt : Int -> @T@
fromInt n =
    fromInt n


{-| (kernel) the number as an `Int`, @EXT@
-}
toInt : @T@ -> Int
toInt a =
    toInt a


{-| (kernel) the decimal text@U64@
-}
toString : @T@ -> String
toString a =
    toString a


and : @T@ -> @T@ -> @T@
and a _ =
    a


or : @T@ -> @T@ -> @T@
or a _ =
    a


xor : @T@ -> @T@ -> @T@
xor a _ =
    a


complement : @T@ -> @T@
complement a =
    a


{-| (kernel) `shiftLeftBy n x`: the count is taken `& @M1@`; bits shifted out are lost
-}
shiftLeftBy : Int -> @T@ -> @T@
shiftLeftBy _ a =
    a


{-| (kernel) `shiftRightBy n x`: the count is taken `& @M1@`; @SHR@
-}
shiftRightBy : Int -> @T@ -> @T@
shiftRightBy _ a =
    a


{-| (kernel) the number of one bits of the @BITS@ bit pattern
-}
popCount : @T@ -> Int
popCount a =
    popCount a


-- IN ELM


minValue : @T@
minValue =
    @MIN@


maxValue : @T@
maxValue =
    @MAX@


{-| The number in a text of decimal digits@SIGNTXT@; `Nothing` when the text is not one or the number does not fit (it does not wrap around).
-}
@FROMSTR@
"""
    ext = "sign extended" if signed else ("read as a signed 64 bit `Int` (the bits are kept)" if T == "Word64" else "zero extended")
    for k, v in [("@MEMBERS@", "".join(member(*m) + "\n" for m in ms).rstrip("\n") + "\n"), ("@FROMSTR@", fromstr), ("@T@", T), ("@BITS@", str(bits)),
                 ("@SGN@", "signed" if signed else "unsigned"), ("@EXT@", ext), ("@U64@", " (unsigned)" if T == "Word64" else ""),
                 ("@M1@", str(bits - 1)), ("@SHR@", "an arithmetic shift (the sign is kept)" if signed else "a logical shift (zeros come in)"),
                 ("@MIN@", minv), ("@MAX@", maxv), ("@SIGNTXT@", " with an optional sign" if signed else "")]:
        tmpl = tmpl.replace(k, v)
    body += tmpl
    return body

def f32_module():
    T = "Float32"
    doc = ("the 32 bit floating point number `Float32`. Every result is rounded to a float (the value is held in a double that is exactly a float), "
           "printed with the shortest digits that read back as the same float. `Float32.fromFloat` rounds, `toFloat` is exact.")
    ms = [("add", "Float32 -> Float32 -> Float32", "a _", "a"), ("sub", "Float32 -> Float32 -> Float32", "a _", "a"),
          ("mul", "Float32 -> Float32 -> Float32", "a _", "a"), ("pow", "Float32 -> Float32 -> Float32", "a _", "a"),
          ("neg", "Float32 -> Float32", "a", "a"), ("abs", "Float32 -> Float32", "a", "a"),
          ("fromInt", "Int -> Float32", "_", "FicFloat32Builtin"), ("compare", "Float32 -> Float32 -> Order", "_ _", "EQ"),
          ("div", "Float32 -> Float32 -> Float32", "a _", "a")]
    body = "module Float32 exposing\n    ( Float32(..)\n    , fromInt, fromFloat, toFloat, toString, fromString\n    )\n\n"
    body += HEADER.replace('@DOC@', doc).replace('@T@', T)
    body += """
import Basics exposing (Float, Int, Order(..))
import Maybe exposing (Maybe(..))
import String exposing (String)


{-| The constructor is never built: it marks the type as the built-in one.
-}
type Float32
    = FicFloat32Builtin
    where
%s

-- KERNEL FUNCTIONS (types only)


{-| (kernel) the `Int` rounded to a float
-}
fromInt : Int -> Float32
fromInt n =
    fromInt n


{-| (kernel) the `Float` rounded to a float (an overflow gives infinity)
-}
fromFloat : Float -> Float32
fromFloat x =
    fromFloat x


{-| (kernel) the same number as a `Float`
-}
toFloat : Float32 -> Float
toFloat a =
    toFloat a


{-| (kernel) the shortest decimal text that reads back as the same float
-}
toString : Float32 -> String
toString a =
    toString a


{-| `Nothing` when the text is not a number (as `String.toFloat`)
-}
fromString : String -> Maybe Float32
fromString s =
    case String.toFloat s of
        Just x ->
            Just (fromFloat x)

        Nothing ->
            Nothing
""" % ("".join(member(*m) + "\n" for m in ms).rstrip("\n") + "\n")
    return body

def int64_module():
    return """module Int64 exposing
    ( Int64
    , fromInt, toInt, toString, fromString, minValue, maxValue
    , and, or, xor, complement, shiftLeftBy, shiftRightBy, popCount
    )

{-| Ficcus (generated by ficcus-tools/gen_sized.py, do not edit; docs/SIZED-PLAN.md): `Int64` is `Int` (one type, no conversion): the 64 bit
signed integer that arithmetic wraps around in (two's complement, no check, no trap). The bit operations are those of `Bitwise64` (the count
is taken `& 63`, `shiftRightBy` is arithmetic). A module `Int64` of the project or of a package wins over this one.
-}

import Basics exposing (Bool, Int, (&&), (+), (-), (==), (/=))
import Bitwise64
import Maybe exposing (Maybe)
import String exposing (String)


type alias Int64 =
    Int


fromInt : Int -> Int64
fromInt n =
    n


toInt : Int64 -> Int
toInt n =
    n


toString : Int64 -> String
toString n =
    String.fromInt n


fromString : String -> Maybe Int64
fromString s =
    String.toInt s


minValue : Int64
minValue =
    -9223372036854775808


maxValue : Int64
maxValue =
    9223372036854775807


and : Int64 -> Int64 -> Int64
and a b =
    Bitwise64.and a b


or : Int64 -> Int64 -> Int64
or a b =
    Bitwise64.or a b


xor : Int64 -> Int64 -> Int64
xor a b =
    Bitwise64.xor a b


complement : Int64 -> Int64
complement a =
    Bitwise64.complement a


shiftLeftBy : Int -> Int64 -> Int64
shiftLeftBy n a =
    Bitwise64.shiftLeftBy n a


shiftRightBy : Int -> Int64 -> Int64
shiftRightBy n a =
    Bitwise64.shiftRightBy n a


popCount : Int64 -> Int
popCount a =
    popCountHelp a 0


popCountHelp : Int -> Int -> Int
popCountHelp n acc =
    if n == 0 then
        acc

    else
        popCountHelp (Bitwise64.and n (n - 1)) (acc + 1)
"""

def float64_module():
    return """module Float64 exposing
    ( Float64
    , fromFloat, toFloat, fromInt, toString, fromString
    )

{-| Ficcus (generated by ficcus-tools/gen_sized.py, do not edit; docs/SIZED-PLAN.md): `Float64` is `Float` (one type, no conversion). A module
`Float64` of the project or of a package wins over this one.
-}

import Basics exposing (Float, Int)
import Maybe exposing (Maybe)
import String exposing (String)


type alias Float64 =
    Float


fromFloat : Float -> Float64
fromFloat x =
    x


toFloat : Float64 -> Float
toFloat x =
    x


fromInt : Int -> Float64
fromInt n =
    Basics.toFloat n


toString : Float64 -> String
toString x =
    String.fromFloat x


fromString : String -> Maybe Float64
fromString s =
    String.toFloat s
"""

def files():
    out = {f"{T}.elm": int_module(T, b, s) for (T, b, s) in INTS}
    out["Float32.elm"] = f32_module()
    out["Int64.elm"] = int64_module()
    out["Float64.elm"] = float64_module()
    return out

if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "overlay")
    bad = 0
    for name, text in sorted(files().items()):
        p = os.path.join(dst, name)
        if "--check" in sys.argv:
            if not os.path.exists(p) or open(p).read() != text:
                print("differs:", name); bad = 1
        else:
            open(p, "w").write(text)
    sys.exit(bad)
