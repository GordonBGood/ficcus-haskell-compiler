#!/usr/bin/env python3
"""The no-RC output is the oracle of stage (iv): the C text that a compiler makes WITHOUT --rc for the 16 suite programs must not
change (so the no-RC programs, whose large builds never free and need gigabytes, need not be run again).

The C text has two parts: the runtime (runtime/*.h, embedded at the top of every generated file) and the code generated for the
program, which starts at the line "generated by the Ficcus compiler". The reference is a file in the repository,
ficcus-tests/expected/norc_identity.sha256: for each program a SHA-256 of each part, and the binary that made it. The generated part is
the oracle and must never change unless the slice changes the no-RC code on purpose; a change of the runtime alone (new functions for the
counted build) is reported as "RUNTIME CHANGED" and is also a failure until it is accepted with --update. Check (default, exit 1 on any
difference):

  python3 ficcus-tests/norc_identity.py --new bin/elmficNN --elm-home H

Refresh (only when a slice changes the no-RC C text ON PURPOSE; it never happens as a side effect of a check):

  python3 ficcus-tests/norc_identity.py --new bin/elmficNN --elm-home H --update --reason "why the text changes"

--update needs --reason, prints every program whose hash changes, rewrites the reference file and appends a line (date, binary,
reason, changed programs) to ficcus-tests/expected/norc_identity.log. Both files are tracked, so the refresh is a visible diff in
the commit. A program that does not compile, or is missing from the reference, is never written silently: --update refuses.

  --old bin/elmficOLD   compares two binaries directly instead of the reference file (the S3 way)."""
import argparse, datetime, hashlib, json, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(HERE, "expected", "norc_identity.sha256")
LOG = os.path.join(HERE, "expected", "norc_identity.log")


def c_text(elm, home, src, out, flags="--no-rc"):
    # `--no-rc` is explicit (the default of the compiler may be --rc); a compiler from before S5 does not know the flag: retry without
    p = subprocess.run([os.path.join(HERE, "ficc"), src, "-o", out],
                       env=dict(os.environ, FICCUS_ELM=os.path.abspath(elm), ELM_HOME=home, FICCUS_FLAGS=flags), capture_output=True, text=True)
    if p.returncode != 0 and flags: return c_text(elm, home, src, out, "")
    return open(out, "rb").read() if p.returncode == 0 and os.path.exists(out) else None


MARK = b"/* generated by the Ficcus compiler"


def split_text(text):
    i = text.find(MARK)
    return (text[:i], text[i:]) if i >= 0 else (text, b"")


def hashes(text):
    rt, gen = split_text(text)
    return (hashlib.sha256(gen).hexdigest(), hashlib.sha256(rt).hexdigest())


def read_ref():
    ref, binary = {}, "?"
    if os.path.exists(REF):
        for l in open(REF):
            if l.startswith("# binary:"): binary = l.split(":", 1)[1].strip()
            elif l.strip() and not l.startswith("#"):
                g, r, n = l.split(); ref[n] = (g, r)
    return ref, binary


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--new", required=True); ap.add_argument("--elm-home", required=True)
    ap.add_argument("--old", default=None, help="compare with this binary instead of the reference file")
    ap.add_argument("--update", action="store_true"); ap.add_argument("--reason", default=None)
    a = ap.parse_args()
    if a.update and (not a.reason or a.old): ap.error("--update needs --reason \"...\" (and no --old)")
    suite = json.load(open(os.path.join(HERE, "runall", "suite.json")))["tests"]
    ref, ref_bin = read_ref()
    tmp = tempfile.mkdtemp()
    bad, new = 0, {}
    for t in suite:
        n = t["name"]
        src = os.path.normpath(os.path.join(HERE, "runall", t["fic"]))
        text = c_text(a.new, a.elm_home, src, os.path.join(tmp, n + "_new.c"))
        new[n] = hashes(text) if text is not None else None
        if a.old:
            old = c_text(a.old, a.elm_home, src, os.path.join(tmp, n + "_old.c"))
            want = hashes(old) if old is not None else None
        else:
            want = ref.get(n)
        if new[n] is None or want is None: status = "NOT IN REFERENCE / COMPILE FAIL"
        elif new[n][0] != want[0]: status = "DIFFERENT (the generated code changed)"
        elif new[n][1] != want[1]: status = "RUNTIME CHANGED (the generated code is identical)"
        else: status = "identical"
        bad += 0 if status == "identical" else 1
        print("%-22s %s" % (n, status))
    print("no-RC C text: %d of %d identical to %s" % (len(suite) - bad, len(suite), a.old or "the reference (%s)" % ref_bin))
    if not a.update: return 1 if bad else 0
    if any(v is None for v in new.values()): print("refusing to update: a program does not compile"); return 1
    gen_changed = [n for n in new if n in ref and ref[n][0] != new[n][0]]
    rt_changed = [n for n in new if n in ref and ref[n][1] != new[n][1]]
    with open(REF, "w") as f:
        f.write("# SHA-256 of the generated part and of the runtime part of the no-RC C text of the 16 suite programs (ficcus-tests/norc_identity.py).\n# Refresh only with --update --reason.\n")
        f.write("# binary: %s\n" % os.path.basename(a.new))
        for n in new: f.write("%s %s %s\n" % (new[n][0], new[n][1], n))
    with open(LOG, "a") as f:
        f.write("%s  %s  generated part changed: %s  runtime part changed: %s  reason: %s\n" % (datetime.date.today().isoformat(), os.path.basename(a.new),
                ",".join(gen_changed) or "none", "all" if len(rt_changed) == len(new) else (",".join(rt_changed) or "none"), a.reason))
    print("reference updated: generated part changed in %d programs, runtime part in %d" % (len(gen_changed), len(rt_changed)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
