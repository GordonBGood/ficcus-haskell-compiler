#!/usr/bin/env python3
"""gen_cases.py -- writes the attach cases `sized-*` (ficcus-tests/attach/cases/) with their expected.out computed by the Python model
(sizedmodel.py): boundary values of every operation of every type (all pairs), literals, conversions, keys and sorting, Int64/Float64.
The cases are checked in; rerun after a change of the model. Usage: python3 ficcus-tests/sized/gen_cases.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sizedmodel import *

HERE = os.path.dirname(os.path.abspath(__file__))
CASES = os.path.join(HERE, "..", "attach", "cases")

PRE = """module Main exposing (main)

import Dict
import Set
%s

logAll : List String -> ()
logAll items =
    List.foldl (\\s acc -> let _ = Debug.log "r" s in acc) () items

"""
POST = """
main : Program () () ()
main =
    Platform.worker
        { init =
            \\_ ->
                let
                    _ =
                        logAll
%s
                in
                ( (), Cmd.none )
        , update = \\_ m -> ( m, Cmd.none )
        , subscriptions = \\_ -> Sub.none
        }
"""

def write_case(name, src, lines):
    d = os.path.join(CASES, name)
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "Main.elm"), "w").write(src)
    open(os.path.join(d, "case.json"), "w").write('{"desc": "sized integers and Float32 (generated by ficcus-tests/sized/gen_cases.py)", "c_only": true}\n')
    open(os.path.join(d, "expected.out"), "w").write("".join('r: "%s"\n' % l for l in lines))

def listsrc(exprs):
    return "\n".join("                            %s %s" % ("[" if i == 0 else ",", e) for i, e in enumerate(exprs)) + "\n                            ]\n"

def bool_s(b): return "True" if b else "False"

def int_boundary(t):
    M, T = t.name, t.name
    vals = boundary(t)
    shifts = [0, 1, 7, 8, 15, 16, 31, 32, 63, 64, -1]
    elm = ["import %s exposing (%s)" % (M, T), "", "",
           "vals : List %s" % T, "vals =", "    List.map %s.fromInt [ %s ]" % (M, ", ".join(str(t.toint(v)) for v in vals)), "",
           "pairs : List ( %s, %s )" % (T, T), "pairs =", "    List.concatMap (\\a -> List.map (\\b -> ( a, b )) vals) vals", "",
           "row2 : String -> (%s -> %s -> String) -> String" % (T, T),
           "row2 name f =", "    name ++ \" \" ++ String.join \" \" (List.map (\\( a, b ) -> f a b) pairs)", "",
           "row1 : String -> (%s -> String) -> String" % T,
           "row1 name f =", "    name ++ \" \" ++ String.join \" \" (List.map f vals)", ""]
    exprs, expected = [], []
    def bin(name, expr, fn):
        exprs.append('row2 "%s" (\\a b -> %s)' % (name, expr))
        expected.append(name + " " + " ".join(fn(a, b) for a in vals for b in vals))
    def una(name, expr, fn):
        exprs.append('row1 "%s" (\\a -> %s)' % (name, expr))
        expected.append(name + " " + " ".join(fn(a) for a in vals))
    S = lambda x: str(x)
    bin("add", "%s.toString (a + b)" % M, lambda a, b: S(t.add(a, b)))
    bin("sub", "%s.toString (a - b)" % M, lambda a, b: S(t.sub(a, b)))
    bin("mul", "%s.toString (a * b)" % M, lambda a, b: S(t.mul(a, b)))
    bin("pow", "%s.toString (a ^ b)" % M, lambda a, b: S(t.pow(a, b)))
    bin("idiv", "%s.toString (a // b)" % M, lambda a, b: S(t.idiv(a, b)))
    bin("modBy", "%s.toString (modBy a b)" % M, lambda a, b: S(t.mod(a, b)))
    bin("remainderBy", "%s.toString (remainderBy a b)" % M, lambda a, b: S(t.rem(a, b)))
    bin("and", "%s.toString (%s.and a b)" % (M, M), lambda a, b: S(t.and_(a, b)))
    bin("or", "%s.toString (%s.or a b)" % (M, M), lambda a, b: S(t.or_(a, b)))
    bin("xor", "%s.toString (%s.xor a b)" % (M, M), lambda a, b: S(t.xor(a, b)))
    bin("lt", "Debug.toString (a < b)", lambda a, b: bool_s(a < b))
    bin("le", "Debug.toString (a <= b)", lambda a, b: bool_s(a <= b))
    bin("gt", "Debug.toString (a > b)", lambda a, b: bool_s(a > b))
    bin("ge", "Debug.toString (a >= b)", lambda a, b: bool_s(a >= b))
    bin("eq", "Debug.toString (a == b)", lambda a, b: bool_s(a == b))
    bin("ne", "Debug.toString (a /= b)", lambda a, b: bool_s(a != b))
    bin("compare", "Debug.toString (compare a b)", lambda a, b: t.cmp(a, b))
    bin("max", "%s.toString (max a b)" % M, lambda a, b: S(max(a, b)))
    bin("min", "%s.toString (min a b)" % M, lambda a, b: S(min(a, b)))
    una("neg", "%s.toString (-a)" % M, lambda a: S(t.neg(a)))
    una("negate", "%s.toString (negate a)" % M, lambda a: S(t.neg(a)))
    una("abs", "%s.toString (abs a)" % M, lambda a: S(t.abs(a)))
    una("complement", "%s.toString (%s.complement a)" % (M, M), lambda a: S(t.complement(a)))
    una("popCount", "String.fromInt (%s.popCount a)" % M, lambda a: S(t.popcount(a)))
    una("toInt", "String.fromInt (%s.toInt a)" % M, lambda a: S(t.toint(a)))
    una("toString", "%s.toString a" % M, lambda a: S(a))
    una("roundtrip", "%s.toString (%s.fromInt (%s.toInt a))" % (M, M, M), lambda a: S(t.fromint(t.toint(a))))
    for n in shifts:
        una("shl%d" % n, "%s.toString (%s.shiftLeftBy (%d) a)" % (M, M, n), lambda a, n=n: S(t.shl(n, a)))
        una("shr%d" % n, "%s.toString (%s.shiftRightBy (%d) a)" % (M, M, n), lambda a, n=n: S(t.shr(n, a)))
    una("minmax", "%s.toString %s.minValue ++ \"/\" ++ %s.toString %s.maxValue" % (M, M, M, M), lambda a: "%d/%d" % (t.lo, t.hi))
    src = PRE % "\n".join(elm[:-1]) + POST % listsrc(exprs)
    return src, expected

def f32_case():
    t = BY_NAME["Float32"]
    vals = fvals()
    def lit(x):
        if x != x: return "(0 / 0)"
        if np.isinf(x): return "(1 / 0)" if x > 0 else "(-1 / 0)"
        return repr(float(x)).replace("e+", "e")
    elm = ["import Float32 exposing (Float32)", "", "", "vals : List Float32", "vals =", "    List.map Float32.fromFloat [ %s ]" % ", ".join(lit(x) for x in vals), "",
           "pairs : List ( Float32, Float32 )", "pairs =", "    List.concatMap (\\a -> List.map (\\b -> ( a, b )) vals) vals", "",
           "row2 : String -> (Float32 -> Float32 -> String) -> String", "row2 name f =", "    name ++ \" \" ++ String.join \" \" (List.map (\\( a, b ) -> f a b) pairs)", "",
           "row1 : String -> (Float32 -> String) -> String", "row1 name f =", "    name ++ \" \" ++ String.join \" \" (List.map f vals)"]
    exprs, expected = [], []
    def bin(name, expr, fn):
        exprs.append('row2 "%s" (\\a b -> %s)' % (name, expr)); expected.append(name + " " + " ".join(fn(a, b) for a in vals for b in vals))
    def una(name, expr, fn):
        exprs.append('row1 "%s" (\\a -> %s)' % (name, expr)); expected.append(name + " " + " ".join(fn(a) for a in vals))
    M = "Float32"
    bin("add", "%s.toString (a + b)" % M, lambda a, b: t.tostr(t.add(a, b)))
    bin("sub", "%s.toString (a - b)" % M, lambda a, b: t.tostr(t.sub(a, b)))
    bin("mul", "%s.toString (a * b)" % M, lambda a, b: t.tostr(t.mul(a, b)))
    bin("div", "%s.toString (a / b)" % M, lambda a, b: t.tostr(t.div(a, b)))
    bin("lt", "Debug.toString (a < b)", lambda a, b: bool_s(t.lt(a, b)))
    bin("le", "Debug.toString (a <= b)", lambda a, b: bool_s(t.le(a, b)))
    bin("gt", "Debug.toString (a > b)", lambda a, b: bool_s(t.gt(a, b)))
    bin("ge", "Debug.toString (a >= b)", lambda a, b: bool_s(t.ge(a, b)))
    bin("eq", "Debug.toString (a == b)", lambda a, b: bool_s(bool(a == b)))
    bin("compare", "Debug.toString (compare a b)", lambda a, b: t.cmp(a, b))
    una("neg", "%s.toString (-a)" % M, lambda a: t.tostr(t.neg(a)))
    una("abs", "%s.toString (abs a)" % M, lambda a: t.tostr(t.abs(a)))
    una("toFloat", "String.fromFloat (%s.toFloat a)" % M, lambda a: fjs(float(a)))
    una("debug", "Debug.toString a", lambda a: t.tostr(a))
    una("round", "%s.toString (%s.fromFloat (%s.toFloat a))" % (M, M, M), lambda a: t.tostr(a))
    # the power at a few values (libm and fdlibm may differ in the last bit of the double, the float is rounded once)
    small = [np.float32(x) for x in (0.5, 1.0, 2.0, 3.0, 10.0, -2.0)]
    exprs.append('"pow " ++ String.join " " (List.map (\\( a, b ) -> %s.toString (a ^ b)) [ %s ])' % (
        M, ", ".join("( %s.fromFloat %s, %s.fromFloat %s )" % (M, lit(a), M, lit(b)) for a in small for b in small)))
    expected.append("pow " + " ".join(t.tostr(t.pow(a, b)) for a in small for b in small))
    src = PRE % "\n".join(elm) + POST % listsrc(exprs)
    return src, expected

def fjs(x):
    """a Float as JavaScript prints it (for toFloat of a float32 value)"""
    if x != x: return "NaN"
    if math.isinf(x): return "Infinity" if x > 0 else "-Infinity"
    if x == 0: return "0"
    r = repr(abs(x))
    # python repr is the shortest round trip; lay it out as JavaScript does
    from decimal import Decimal
    d = Decimal(r)
    sign, digits, exp = d.as_tuple()
    digits = "".join(map(str, digits)).rstrip("0") or "0"
    n = len(Decimal(r).as_tuple().digits) + exp
    # recompute n from the normalized digits
    mant = Decimal(r).normalize()
    s, dg, ex = mant.as_tuple()
    digits = "".join(map(str, dg)); k = len(digits); n = k + ex
    if k <= n <= 21: out = digits + "0" * (n - k)
    elif 0 < n <= 21: out = digits[:n] + "." + digits[n:]
    elif -6 < n <= 0: out = "0." + "0" * (-n) + digits
    else: out = digits[0] + ("." + digits[1:] if k > 1 else "") + "e" + ("-" if n - 1 < 0 else "+") + str(abs(n - 1))
    return ("-" if x < 0 else "") + out

def lit_case():
    pre = ["import Int8 exposing (Int8)", "import Int16 exposing (Int16)", "import Int32 exposing (Int32)", "import Word8 exposing (Word8)",
           "import Word16 exposing (Word16)", "import Word32 exposing (Word32)", "import Word64 exposing (Word64)", "import Float32 exposing (Float32)"]
    defs = """

a : Int8
a =
    127


b : Int8
b =
    -128


c : Word8
c =
    255


d : Word16
d =
    0xFFFF


e : Word64
e =
    9223372036854775807


f : Int32
f =
    -2147483648


g : Float32
g =
    16777217


h : Float32
h =
    3


i : Word32
i =
    4294967295


j : Int16
j =
    -32768


k : Float32
k =
    -5


big : Float32
big =
    123456789123


classify : Int8 -> String
classify x =
    if x == 0 then
        "zero"

    else if x == 1 then
        "one"

    else if x == -1 then
        "minus one"

    else if x == 127 then
        "max"

    else
        "other"


classifyW : Word8 -> String
classifyW x =
    if x == 255 then
        "max"

    else if x == 0 then
        "zero"

    else
        "other"


bytes : List Word8
bytes =
    [ 0, 1, 255 ]


type alias Pixel =
    { r : Word8, g : Word8, b : Word8 }


px : Pixel
px =
    { r = 255, g = 128, b = 0 }


twice : number -> number
twice x =
    x + x


inc : Int8 -> Int8
inc x =
    x + 1
"""
    exprs = [
        ('Int8.toString a', "127"), ('Int8.toString b', "-128"), ('Word8.toString c', "255"), ('Word16.toString d', "65535"),
        ('Word64.toString e', "9223372036854775807"), ('Int32.toString f', "-2147483648"), ('Float32.toString g', "16777216"),
        ('Float32.toString h', "3"), ('Word32.toString i', "4294967295"), ('Int16.toString j', "-32768"), ('Float32.toString k', "-5"),
        ('Float32.toString big', BY_NAME["Float32"].tostr(np.float32(123456789123))),
        ('classify 0', "zero"), ('classify 1', "one"), ('classify -1', "minus one"), ('classify 127', "max"), ('classify (Int8.fromInt 300)', "other"),
        ('classifyW 255', "max"), ('classifyW (Word8.fromInt -256)', "zero"), ('classifyW 7', "other"),
        ('String.join "," (List.map Word8.toString bytes)', "0,1,255"),
        ('String.join "," (List.map Word8.toString [ px.r, px.g, px.b ])', "255,128,0"),
        ('Int8.toString (twice 60)', "120"), ('Int8.toString (twice 100)', "-56"), ('Word8.toString (twice 200)', "144"),
        ('Int8.toString (inc 127)', "-128"), ('Int8.toString (inc (inc 126))', "-128"),
        ('Debug.toString (a == 127)', "True"), ('Debug.toString (c > 254)', "True"), ('Debug.toString (px == { r = 255, g = 128, b = 0 })', "True"),
        ('Debug.toString px', "{ b = 0, g = 128, r = 255 }"),
        ('Word8.toString (c + 1)', "0"), ('Word8.toString (0 - 1)', "255"), ('Word64.toString (0 - 1)', "18446744073709551615"),
        ('Int8.toString (-b)', "-128"), ('Int8.toString (abs b)', "-128"), ('Word8.toString (negate 1)', "255") if False else ('Word8.toString (negate c)', "1"),
    ]
    src = PRE % "\n".join(pre) + defs + POST % listsrc([e[0] for e in exprs])
    return src, [e[1] for e in exprs]

def main():
    for t in INTS:
        src, exp = int_boundary(t)
        write_case("sized-bound-" + t.name.lower(), src, exp)
    src, exp = f32_case(); write_case("sized-bound-float32", src, exp)
    src, exp = lit_case(); write_case("sized-lit", src, exp)

if __name__ == "__main__":
    main()
