def write_case(name, src, lines):
    d = os.path.join(CASES, name)
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "Main.elm"), "w").write(src)
    open(os.path.join(d, "case.json"), "w").write('{"desc": "sized integers and Float32 (generated by ficus-tests/sized/gen_cases.py)", "c_only": true}\n')
    open(os.path.join(d, "expected.out"), "w").write("".join('r: "%s"\n' % l.replace("\\", "\\\\").replace('"', '\\"') for l in lines))

def listsrc(exprs):
    return "\n".join("                            %s %s" % ("[" if i == 0 else ",", e) for i, e in enumerate(exprs)) + "\n                            ]\n"

def bool_s(b): return "True" if b else "False"

